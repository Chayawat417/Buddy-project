const dictionaries = { th: thai, en: english } as const;
export type TranslationKey = keyof typeof english;
type TranslationParams = Readonly<Record<string, string | number>>;

interface LanguageContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  storageWarning: boolean;
  t: (key: TranslationKey, params?: TranslationParams) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function readSavedLocale(
  storage: Pick<Storage, "getItem">,
): Locale {
  try {
    return storage.getItem(languageStorageKey) === "en" ? "en" : "th";
  } catch {
    return "th";
  }
}

export function saveLocalePreference(
  storage: Pick<Storage, "setItem">,
  locale: Locale,
): boolean {
  try {
    storage.setItem(languageStorageKey, locale);
    return true;
  } catch {
    return false;
  }
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  params: TranslationParams = {},
): string {
  return dictionaries[locale][key].replace(
    /\{(\w+)\}/g,
    (placeholder, name: string) => String(params[name] ?? placeholder),
  );
}

function getInitialLocale(): Locale {
  try {
    return readSavedLocale(window.localStorage);
  } catch {
    return "th";
  }
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(getInitialLocale);
  const [storageWarning, setStorageWarning] = useState(false);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.title =
      locale === "th" ? "Buddy — วางแผนงบประมาณ" : "Buddy — Budget planning";
    const description = document.querySelector<HTMLMetaElement>(
      'meta[name="description"]',
    );
    if (description) {
      description.content =
        locale === "th"
          ? "Buddy สำหรับวางแผนและตรวจสอบงบประมาณส่วนตัวและครอบครัว"
          : "Buddy for planning and tracking personal and family budgets.";
    }
  }, [locale]);

  function setLocale(nextLocale: Locale): void {
    setLocaleState(nextLocale);
    try {
      setStorageWarning(!saveLocalePreference(window.localStorage, nextLocale));
    } catch {
      setStorageWarning(true);
    }
  }

  const value = useMemo<LanguageContextValue>(
    () => ({
      locale,
      setLocale,
      storageWarning,
      t: (key, params) => translate(locale, key, params),
    }),
    [locale, storageWarning],
  );

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage(): LanguageContextValue {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within a LanguageProvider.");
  }
  return context;
}
